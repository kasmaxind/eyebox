export function getVideo(id: string): Video | undefined {
  return [...videos, ...shorts].find((v) => v.id === id);
}

export function getVideosByChannel(channelId: string): Video[] {
  return videos.filter((v) => v.channelId === channelId);
}

export function getRelated(videoId: string, limit = 12): Video[] {
  const current = getVideo(videoId);
  if (!current) return videos.slice(0, limit);
  return videos
    .filter((v) => v.id !== videoId)
    .sort((a, b) => {
      const score = (v: Video) =>
        (v.channelId === current.channelId ? 3 : 0) +
        (v.category === current.category ? 2 : 0) +
        v.tags.filter((t) => current.tags.includes(t)).length;
      return score(b) - score(a);
    })
    .slice(0, limit);
}

export function searchVideos(query: string): Video[] {
  const q = query.trim().toLowerCase();
  if (!q) return videos;
  return [...videos, ...shorts].filter(
    (v) =>
      v.title.toLowerCase().includes(q) ||
      v.description.toLowerCase().includes(q) ||
      v.tags.some((t) => t.includes(q)) ||
      v.category.toLowerCase().includes(q),
  );
}
